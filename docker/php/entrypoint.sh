#!/bin/sh
set -e

# Trust the Novacore CA, so PHP can make HTTPS requests to other local sites
# (WordPress loopback requests, APIs between projects, etc).
if [ -f /etc/novacore/certs/ca.crt ]; then
    cp /etc/novacore/certs/ca.crt /usr/local/share/ca-certificates/novacore.crt
    update-ca-certificates >/dev/null 2>&1 || true
fi

# libcurl (and so PHP's curl extension) always resolves *.localhost to the
# loopback address without asking DNS, so relay this container's loopback web
# ports to nginx. Other lookups reach nginx through its network aliases.
if [ "$1" = php-fpm ]; then
    for port in 80 443; do
        socat "TCP4-LISTEN:$port,bind=127.0.0.1,fork,reuseaddr" "TCP:nginx:$port" &
        socat "TCP6-LISTEN:$port,bind=[::1],fork,reuseaddr" "TCP:nginx:$port" 2>/dev/null &
    done

    # Relay the host's SSH agent (mounted by novacore when it finds one) through
    # a socket www-data owns. The mounted socket's owner and permissions vary
    # between Linux, Docker Desktop and WSL, and often only root can use it.
    if [ -S /run/novacore/host-agent.sock ]; then
        socat "UNIX-LISTEN:/run/novacore/ssh-agent.sock,fork,unlink-early,user=www-data,group=www-data,mode=600" \
            UNIX-CONNECT:/run/novacore/host-agent.sock &
    fi
fi

# SSH config for www-data. Settings here come first, so they win over the
# host's config: always use the relayed agent (the host config may name an
# agent path that only exists on the host, e.g. 1Password's), and skip
# macOS-only options that Linux ssh rejects.
ssh_dir=/var/www/.ssh
mkdir -p "$ssh_dir"
{
    echo "# Generated by novacore when the container starts."
    echo "IgnoreUnknown UseKeychain"
    echo "IdentityAgent /run/novacore/ssh-agent.sock"
    echo "UserKnownHostsFile ~/.ssh/known_hosts /etc/novacore/ssh/known_hosts"
    if [ -f /etc/novacore/ssh/config ]; then
        echo "Include /etc/novacore/ssh/config"
    fi
} > "$ssh_dir/config"
chown -R www-data:www-data "$ssh_dir"
chmod 700 "$ssh_dir"
chmod 600 "$ssh_dir/config"

exec docker-php-entrypoint "$@"
